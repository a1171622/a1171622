"""Generate tests/daten_min.py from SOFiSTiK's sofistik_daten.py.

    python tests/make_daten_min.py [path\\to\\sofistik_daten.py]

sofistik_daten.py belongs to SOFiSTiK and is not committed here.  The tests (and CI, which has no
SOFiSTiK) need only the record classes that sofistik_mcp/results.py, cdbio.py and tests/fake_cdb.py
use.  This script copies exactly those classes, field for field (names, ctypes type expressions,
order, _pack_ if any), as text from the real file, so nothing is retyped by hand.
tests/test_daten_min.py checks the result against the real file whenever that file is available.
"""
from __future__ import annotations

import ast
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "daten_min.py")

# every sofistik_daten class the source and the fake cdb use (grep '"C[A-Z_]*"' sofistik_mcp tests)
CLASSES = (
    "CMAT", "CMAT_STEE",                    # 1/NR     materials
    "CSECT", "CSECT_PRO", "CSECT_TXT",      # 9/NR     sections
    "CSYST",                                # 10/00    system
    "CGRP",                                 # 11/00    groups
    "CLC_CTRL", "CLC_EIGE",                 # 12/LC    load cases
    "CLC_ACT",                              # 14/ID    actions
    "CNODE",                                # 20/00    nodes
    "CN_DISPC", "CN_DISP",                  # 24/LC    node results
    "CBEAM", "CBEAM_SCT",                   # 100/00   beams
    "CBEAM_FOC", "CBEAM_FOR",               # 102/LC   beam forces
    "CTRUS_RES",                            # 152/LC   truss results
    "CCABL_RES",                            # 162/LC   cable results
)

DEFAULT_SOURCES = (
    os.environ.get("SOFISTIK_DATEN"),
    r"C:\Program Files\SOFiSTiK\2027\SOFiSTiK 2027\interfaces\examples\python\sofistik_daten.py",
    os.path.join(HERE, "..", "..", "reports", "sofistik_report", "vendor", "sofistik_daten.py"),
    "/mnt/project-files/reports/sofistik_report/vendor/sofistik_daten.py",
)


def find_source() -> str | None:
    for p in DEFAULT_SOURCES:
        if p and os.path.isfile(p):
            return os.path.abspath(p)
    return None


def extract(src_text: str, names=CLASSES) -> list[dict]:
    """[{name, comment, fields: [(name, type_src)], pack}] for the named classes, in names order."""
    tree = ast.parse(src_text)
    lines = src_text.split("\n")
    found = {}
    for node in tree.body:
        if not isinstance(node, ast.ClassDef) or node.name not in names:
            continue
        if [ast.unparse(b) for b in node.bases] != ["Structure"]:
            raise SystemExit(f"{node.name}: unexpected base classes {[ast.unparse(b) for b in node.bases]}")
        head = lines[node.lineno - 1]
        comment = head.split("#", 1)[1].strip() if "#" in head else ""
        fields, pack = None, None
        for st in node.body:
            if isinstance(st, ast.Assign) and len(st.targets) == 1 and isinstance(st.targets[0], ast.Name):
                tgt = st.targets[0].id
                if tgt == "_fields_":
                    fields = []
                    for elt in st.value.elts:
                        fname = ast.literal_eval(elt.elts[0])
                        ftype = ast.unparse(elt.elts[1])
                        if len(elt.elts) != 2:
                            raise SystemExit(f"{node.name}.{fname}: bit fields are not supported")
                        fields.append((fname, ftype))
                elif tgt == "_pack_":
                    pack = ast.literal_eval(st.value)
                elif tgt == "_anonymous_":
                    raise SystemExit(f"{node.name}: _anonymous_ is not supported")
        if fields is None:
            raise SystemExit(f"{node.name}: no _fields_")
        found[node.name] = {"name": node.name, "comment": comment, "fields": fields, "pack": pack}
    missing = [n for n in names if n not in found]
    if missing:
        raise SystemExit(f"Not in the source file: {missing}")
    return [found[n] for n in names]


def render(classes: list[dict], source_name: str, version_line: str) -> str:
    used = set()
    for c in classes:
        for _f, t in c["fields"]:
            used.update(re.findall(r"\b(c_[a-z0-9_]+)\b", t))
    out = [
        '"""Minimal copy of SOFiSTiK\'s sofistik_daten.py for the tests (generated, do not edit).',
        "",
        "Generated by tests/make_daten_min.py from " + source_name
        + (f" ({version_line})" if version_line else "") + ".",
        "Only the record classes sofistik_mcp and tests/fake_cdb.py use, copied field for field.",
        "tests/test_daten_min.py compares every class with the real file whenever it is available.",
        '"""',
        "from ctypes import Structure, " + ", ".join(sorted(used)),
        "",
        "CLASSES = (",
        *[f"    {c['name']!r}," for c in classes],
        ")",
    ]
    for c in classes:
        out += ["", "", f"class {c['name']}(Structure):" + (f"  # {c['comment']}" if c["comment"] else "")]
        if c["pack"] is not None:
            out.append(f"    _pack_ = {c['pack']!r}")
        out.append("    _fields_ = [")
        for fname, ftype in c["fields"]:
            out.append(f"        ({fname!r}, {ftype}),")
        out.append("    ]")
    out.append("")
    return "\n".join(out)


def main(argv):
    src = argv[1] if len(argv) > 1 else find_source()
    if not src or not os.path.isfile(src):
        print("sofistik_daten.py not found; give its path as the argument or set SOFISTIK_DATEN.",
              file=sys.stderr)
        return 1
    with open(src, encoding="utf-8", errors="replace") as f:
        text = f.read()
    classes = extract(text)
    code = render(classes, "SOFiSTiK 2027 sofistik_daten.py", "")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(code)
    print(f"wrote {OUT}: {len(classes)} classes from {src}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
