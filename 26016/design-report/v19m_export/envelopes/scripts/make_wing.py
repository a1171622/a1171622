"""Writes ../26016_env_wing.dat: one WinGRAF program, one sheet per picture, ULS envelope max (red) and min (blue)
overlaid, labels only above a threshold (largest local extremes), structure lines grey, then PLBCONVERTER to PNG.
Reads ../env_table_ULS.json for the extremes (scale and label threshold). Writes ../pictures.json (the picture list)."""
import json, math, os

HERE = os.path.dirname(os.path.abspath(__file__)); OUT = os.path.dirname(HERE)
T = {g["group"]: g for g in json.load(open(os.path.join(OUT, "env_table_ULS.json")))["groups"]}
LC = {"N": (4321, 4322), "VY": (4323, 4324), "VZ": (4325, 4326), "MT": (4327, 4328), "MY": (4329, 4330), "MZ": (4331, 4332)}
KEY = {"N": "N", "VY": "Vy", "VZ": "Vz", "MT": "Mt", "MY": "My", "MZ": "Mz"}
UNIT = {"N": "kN", "VY": "kN", "VZ": "kN", "MT": "kNm", "MY": "kNm", "MZ": "kNm"}
ISO = "VIEW TYPE DIRE X 1 Y 1.4 Z -2.6 AXIS NEGZ"        # steep isometric for floor framing
ISO3D = "VIEW TYPE DIRE X 1 Y 1.4 Z -0.8 AXIS NEGZ"      # 3D view as W1 / W4
PLAN = "VIEW TYPE DIRE X 0 Y 0 Z -1 AXIS NEGY"           # true top view, X right, Y up
EXT = "VIEW TYPE DIRE X -1 Y 0.35 Z -0.45 AXIS NEGZ"     # external stair from outside (as W8)
VERT = [11, 12, 13, 14, 21, 23, 24, 31]


def nice(v):
    """engineering-rounded scale value"""
    e = 10 ** math.floor(math.log10(v)); m = v / e
    return [s for s in (1, 2, 2.5, 5, 10) if s >= m - 1e-9][0] * e


def ext(groups, q):
    k = KEY[q]
    mx = max(groups, key=lambda g: T[g][f"{k}_max"]); mn = min(groups, key=lambda g: T[g][f"{k}_min"])
    return (T[mx][f"{k}_max"], mx), (T[mn][f"{k}_min"], mn)


PICS = []
RING = json.load(open(os.path.join(HERE, "ring85_ranges.json")))
SEXT = json.load(open(os.path.join(HERE, "storey_ext.json")))
def pic(name, title, groups, q, view, H=30, frac=0.45, unit=None, length=2.5, extra=(), amax=None, sub=None):
    (vmax, gmax), (vmin, gmin) = ext(groups, q)
    if sub:
        vmax, vmin = [round(v, 2) for v in SEXT[sub][q]]; gmax = gmin = sub
    a = amax or max(abs(vmax), abs(vmin))
    PICS.append(dict(name=name, title=title, groups=groups, q=q, view=view, H=H, extra=list(extra),
                     unit=unit or nice(a / length), thr=round(frac * a, 1 if a < 20 else 0),
                     max=vmax, max_group=gmax, min=vmin, min_group=gmin, lcs=LC[q]))

# b-d floors: isometric (My, Vz, N act / are drawn in the vertical plane), Mz of Level 1 in true plan
for lv, g in (("L1", 15), ("L2", 25), ("RF", 35)):
    lab = {"L1": "Level 1", "L2": "Level 2", "RF": "Roof"}[lv]
    for q in ("MY", "VZ", "N"):
        if q == "N":   # N is near constant per member: thin bars, label only the largest
            pic(f"{lv}_{KEY[q]}", f"{lab} framing (group {g}) {KEY[q]}", [g], q, ISO, frac=0.6, length=0.8)
        else:
            pic(f"{lv}_{KEY[q]}", f"{lab} framing (group {g}) {KEY[q]}", [g], q, ISO, frac=0.35 if (lv, q) == ("L2", "MY") else 0.45)
pic("L1_Mz_plan", "Level 1 framing (group 15) Mz, plan", [15], "MZ", PLAN, frac=0.3)
pic("L1_ring85_Mz_plan", "Level 1 ring r 8.5 only (group 15) Mz, plan", [15], "MZ", PLAN, frac=0.3, unit=1, sub="ring85",
    extra=["SEL ETYP BEAM TYPE NO VAL1 %d VAL2 %d" % tuple(r) for r in RING])
# e vertical structure, one storey per picture (BOX by height)
SR = json.load(open(os.path.join(HERE, "storey_ranges.json")))
STOREY = (("G-L1", "ground to Level 1", -1, 4.10), ("L1-L2", "Level 1 to Level 2", 4.00, 8.10), ("L2-RF", "Level 2 to roof", 8.00, 12.5))
for sid, slab, z0, z1 in STOREY:
    for q in ("N", "MY", "MZ"):
        pic(f"V_{sid}_{KEY[q]}", f"columns and rakers {slab} (groups {', '.join(map(str, VERT))}) {KEY[q]}", VERT, q, ISO3D, H=24,
            frac=0.6 if q == "N" else 0.45, unit={"N": 200, "MY": 10, "MZ": 10}[q], sub=sid,
            extra=["SEL ETYP BEAM TYPE NO VAL1 %d VAL2 %d" % tuple(r) for r in SR[sid]])
# g stairs
for q in ("N", "MY", "VZ"):
    pic(f"S_int_{KEY[q]}", f"internal stairs (groups 60, 61) {KEY[q]}", [60, 61], q, ISO3D, H=24, frac=0.85 if q == "N" else 0.45,
        length=1.2 if q == "N" else 2.0)
for q in ("N", "MY", "VZ"):
    pic(f"S_ext_{KEY[q]}", f"external stair (group 62) {KEY[q]}", [62], q, EXT, H=24, frac=0.85 if q == "N" else 0.45,
        length=1.2 if q == "N" else 2.0)

L = ["$ 26016 v19m - WinGRAF ULS envelope pictures for the report appendix (generated by scripts/make_wing.py)",
     "$ Reads 26016_env_v19m.cdb = COPY of 26016_check_v19m.cdb. Envelope LCs from the model's own MAXIMA COMB 3:",
     "$ 4321/4322 N, 4323/4324 Vy, 4325/4326 Vz, 4327/4328 Mt, 4329/4330 My, 4331/4332 Mz (MAXD / MIND).",
     "$ Each sheet: LC MAXD in red AND LC MIND in blue, labels only where |value| > threshold (SCH2 MIN1/MAX1).",
     "+PROG WING urs:1",
     "HEAD 26016 v19m ULS envelopes",
     "DB 1 TITL '26016_env_v19m.cdb'",
     "$ ---- P00 key picture: beam groups",
     "SIZE TYPE 9 W 25.5 H 30 FORM URS SC 0 MARG NO",
     "SCHH H1 0.35 H5 0 H6 0.33 H10 0.35 REVI EXTR TREV AMAX ND 1",
     ISO3D,
     "GRP 11,12,13,14,15,21,23,24,25,31,35,60,61,62",
     "STRU NUME GRP NUMN BEAM FILL VARC"]
for i, p in enumerate(PICS, 1):
    lmax, lmin = p["lcs"]; u = UNIT[p["q"]]; k = KEY[p["q"]]
    L += [f"$ ---- P{i:02d} {p['name']}: {p['title']}, scale 1 cm = {p['unit']:g} {u}, labels |value| > {p['thr']:g} {u}",
          f"SIZE TYPE 9 W 25.5 H {p['H']} FORM URS SC 0 MARG NO",
          "SEL",
          "SCHH H1 0.35 H5 0 H6 0.375 H10 0.35 REVI EXTR TREV AMAX ND 1",
          p["view"],
          "GRP " + ",".join(map(str, p["groups"])),
          *p["extra"],
          "COLO C12 9001 C4 9001",
          f"SCH2 MIN1 {p['thr']:g} MAX1 {-p['thr']:g}",
          f"LC {lmax} TITL '{k} {u}: max red/min blue' ; COLO C13 2101 C14 2101 ; BEAM TYPE {p['q']} UNIT {p['unit']:g} STAT MAX",
          "AND",
          f"LC {lmin} ; COLO C13 4101 C14 4101 ; BEAM TYPE {p['q']} UNIT {p['unit']:g} STAT MAX"]
L += ["END", "", "+PROG PLBCONVERTER urs:9", "HEAD export the WinGRAF pictures as PNG",
      "IMG FNR 'wing_img/img_%number%.%ext%' OVRT YES FMT PNG", "END", ""]
open(os.path.join(OUT, "26016_env_wing.dat"), "w", newline="\r\n").write("\n".join(L))
json.dump(PICS, open(os.path.join(OUT, "pictures.json"), "w"), indent=1)
for i, p in enumerate(PICS, 1):
    print(f"P{i:02d} {p['name']:12s} unit {p['unit']:g} thr {p['thr']:g} max {p['max']} (g{p['max_group']}) min {p['min']} (g{p['min_group']})")





